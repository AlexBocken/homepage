const normalise = (text: string) => text.replace(/\s+/g, ' ').trim();
const GERMAN = new Map(GERMAN_TITLES.map(([from, to]) => [normalise(from), to]));

/** A heading split into what kind of division it is and what it is called. */
function split(lang: CouncilLang, raw: string): { label: string; title: string } {
	const text = normalise(raw);
	for (const [pattern, name] of LABEL[lang]) {
		const keyword = pattern.exec(text);
		if (!keyword) continue;
		const rest = text.slice(keyword[0].length);
		const number = NUMBER.exec(rest);
		if (!number) return { label: name, title: rest.trim() };
		return { label: `${name} ${number[1]}`, title: rest.slice(number[0].length).trim() };
	}
	return { label: '', title: text };
}

/** A division's heading as the reader shows it: "Titel VII · Ehe". */
export function readable(lang: CouncilLang, raw: string): string {
	const { label, title } = split(lang, raw);
	const set = !title ? '' : lang === 'de' ? (GERMAN.get(title) ?? title) : lang === 'en' ? titleCaseEn(title) : sentenceCaseLa(title);
	return [label, set].filter(Boolean).join(' · ');
}

/** German headings the table has no entry for — the importer reports them. */
export function missingGerman(raw: string): string | null {
	const { title } = split('de', raw);
	if (!title || GERMAN.has(title)) return null;
	return title === title.toUpperCase() ? title : null;
}
