/**
 * Blurred placeholders for the commentators' portraits.
 *
 *   pnpm bible:fathers:blur        # also run by `pnpm bible:fathers` after cutting
 *
 * The round avatars (FatherAvatar.svelte) are lazy and appear by the dozen
 * under the verses, so each shows its blur until its WebP lands, like the
 * hikes photos and the artworks under static/. The placeholders come from
 * the 96 px crops that `pnpm bible:fathers` cuts, boxed smaller than the
 * default since a disc is at most 112 px on screen, and are written to
 * src/lib/data/fathersBlur.generated.ts keyed by commentator id — a few
 * hundred bytes each, so the manifest is committed and imported whole.
 *
 * They are kept out of the static/ manifest (scripts/build-static-blur.ts
 * skips the fathers folder): that one is keyed by URL and also covered the
 * uncropped originals nobody displays, four entries per face.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { FATHERS } from '../src/lib/faith/fathers';
import { blurPlaceholder } from '../src/lib/server/lqip';

const DIR = path.resolve('static', 'glaube', 'fathers');
const OUT = path.resolve('src', 'lib', 'data', 'fathersBlur.generated.ts');
/** Longest side of the embedded source: a 24–112 px disc needs no more. */
const BOX = 10;

export async function buildFathersBlur(): Promise<number> {
	const out: Record<string, string> = {};
	for (const fa of FATHERS) {
		if (!fa.portrait) continue;
		const src = path.join(DIR, `${fa.id}-96.webp`);
		let buf: Buffer;
		try {
			buf = await fs.readFile(src);
		} catch {
			console.warn(`[fathers-blur] ${fa.id}: ${path.basename(src)} missing — run pnpm bible:fathers`);
			continue;
		}
		const blur = await blurPlaceholder(buf, BOX);
		if (blur) out[fa.id] = blur;
	}
	const banner = '// AUTO-GENERATED by scripts/build-fathers-blur.ts — do not edit by hand.\n\n';
	await fs.writeFile(OUT, `${banner}export const FATHERS_BLUR: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`);
	console.log(`[fathers-blur] ${Object.keys(out).length} placeholders → ${path.relative(process.cwd(), OUT)}`);
	return Object.keys(out).length;
}

// Runs on import: `build-fathers.ts` loads this module dynamically once the
// crops are cut (vite-node leaves no entry path in argv to tell the two apart).
await buildFathersBlur();
